ENTRY = re.compile(
    r"(?:^|(?<=[\s(]))(?P<num>\d{1,3})(?:\s*[—\-]\s*(?P<num_to>\d{1,3}))?\s*[.,]?\s*"
    r"(?:[(\[](?P<map>\d{1,3})(?:\s*[—\-]\s*\d{1,3})?[)\]]\s*[.,]?)?\s+"
    r"(?P<name>[А-ЯЁІЎ](?:[А-ЯЁІЎ\-—]|\s(?=[А-ЯЁІЎ\-—]))+"
    r"(?:\s*\([^()]{1,40}\))*"
    r"(?:\s*[—\-]\s*[А-ЯЁІЎ][А-ЯЁІЎ\s]+(?:\s*\([^()]{1,40}\))*)?)(?=\s*[,.;]\s)")


def district_for(printed_page):
    best = None
    for obl, dists in TOC.items():
        for d, p in dists:
            if p <= printed_page:
                best = (obl, d, p)
    return best[:2] if best else (None, None)


def norm(text):
    text = text.replace("\xad\n", "").replace("\xad", "")
    text = re.sub(r"(\w)-\n(\w)", r"\1\2", text)
    text = re.sub(r"\s*\n\s*", " ", text)
    return re.sub(r"\s{2,}", " ", text)


def main():
    pdf, out_jsonl, out_csv = sys.argv[1:4]
    d = pymupdf.open(pdf)
    # склеиваем каталог, запоминая, где начинается каждая печатная страница
    chunks, marks, pos = [], [], 0
    for printed in range(CATALOG_START, CATALOG_END + 1):
        t = norm(d[printed + PDF_OFFSET - 1].get_text())
        t = re.sub(r"^\s*\d{1,3}\s+", "", t)  # номер страницы в начале
        marks.append((pos, printed))
        chunks.append(t + " ")
        pos += len(t) + 1
    full = "".join(chunks)

    def page_at(i):
        p = CATALOG_START
        for start, printed in marks:
            if start <= i:
                p = printed
        return p

    # заголовки областей и районов прямо в тексте каталога
    heads = []
    for h in re.finditer(r"[IVX]+\.\s+([А-ЯЁ]+АЯ)\s+ОБЛАСТЬ", full):
        heads.append((h.start(), "obl", h.group(1).capitalize().replace("ая", "ая")))
    for h in re.finditer(r"\d{1,2}\.\s+([А-ЯЁ\-]+СКИЙ|[А-ЯЁ\-]+ЦКИЙ)\s+РАЙОН", full):
        heads.append((h.start(), "dist", h.group(1).title()))
    heads.sort()
    # 1) все кандидаты; 2) в каждой области — самая длинная цепочка
    # с растущими номерами (ложные срабатывания в неё не попадают)
    cands = {}
    hi, dist = 0, None
    for m in ENTRY.finditer(full):
        while hi < len(heads) and heads[hi][0] <= m.start():
            if heads[hi][1] == "dist":
                dist = heads[hi][2]
            hi += 1
        if re.search(r"РАЙОН|ОБЛАСТЬ", m.group("name")):
            continue
        page = page_at(m.start())
        obl, toc_dist = district_for(page)
        cands.setdefault(obl, []).append(
            (m, int(m.group("num")), page, obl, dist or toc_dist,
             int(m.group("num_to") or m.group("num"))))
    entries, accepted = [], []
    for obl, cs in cands.items():
        n = len(cs)
        best = [1] * n
        prev = [-1] * n
        for i in range(n):
            for j in range(max(0, i - 60), i):
                if 0 < cs[i][1] - cs[j][5] <= 12 and cs[i][5] >= cs[i][1] and best[j] + 1 > best[i]:
                    best[i], prev[i] = best[j] + 1, j
        i = max(range(n), key=lambda k: best[k]) if n else -1
        chain = []
        while i != -1:
            chain.append(cs[i])
            i = prev[i]
        accepted += reversed(chain)
    for k, (m, num, page, obl, dist, num_to) in enumerate(accepted):
        end = accepted[k + 1][0].start() if k + 1 < len(accepted) else len(full)
        body = full[m.end():end].strip(" ,.")
        selsovet = re.match(r"([^,.]{2,40}?)\s+с/с", body)
        refs = re.findall(r"\(([^()]*\d{4}[^()]*)\)", body)
        types = [n for n, rx in TYPES if re.search(rx, body, re.I)]
        cults = [n for n, rx in CULTURES if re.search(rx, body, re.I)]
        e = {
            "source": "Поболь Л.Д. Археологические памятники Белоруссии: Железный век. Мн.: Наука и техника, 1983",
            "oblast": obl, "district": dist, "num": num,
            "num_to": num_to if num_to != num else None,
            "map_num": int(m.group("map")) if m.group("map") else None,
            "name": re.sub(r"\s+", " ", m.group("name")).strip(" -—"),
            "selsovet": selsovet.group(1).strip() if selsovet else None,
            "types": types, "cultures": cults, "page": page,
            "text": body, "refs": refs,
        }
        entries.append(e)
    with open(out_jsonl, "w", encoding="utf-8") as f:
        for e in entries:
            f.write(json.dumps(e, ensure_ascii=False) + "\n")
    with open(out_csv, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Область", "Район", "№", "№ на карте", "Пункт", "Сельсовет",
                    "Тип (авто)", "Культура (авто)", "Стр.", "Описание"])
        for e in entries:
            w.writerow([e["oblast"], e["district"], e["num"], e["map_num"] or "",
                        e["name"], e["selsovet"] or "", "; ".join(e["types"]),
                        "; ".join(e["cultures"]), e["page"], e["text"]])
    # сверка с ожидаемым числом записей по областям
    expect = {"Брестская": 298, "Витебская": 712, "Гомельская": 928,
              "Гродненская": 354, "Минская": 485, "Могилевская": 497}
    for obl, n in expect.items():
        got = [k for e in entries if e["oblast"] == obl
               for k in range(e["num"], (e["num_to"] or e["num"]) + 1)]
        missing = sorted(set(range(1, n + 1)) - set(got))
        print(f"{obl}: найдено {len(got)} из {n}, пропущено {len(missing)}"
              f"{' (напр. ' + str(missing[:8]) + ')' if missing else ''}",
              file=sys.stderr)


if __name__ == "__main__":
    main()
